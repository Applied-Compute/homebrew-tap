#!/usr/bin/env python3
"""Prepare and verify public acshift bundles without accessing Relay source."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = ('darwin-arm64', 'darwin-amd64', 'linux-arm64', 'linux-amd64')
SOURCE = 'https://shift.ac/downloads/cli'
RELEASES = 'https://github.com/Applied-Compute/homebrew-tap/releases/download'


def bundle_digest(path: Path) -> str:
    name = path.name.removesuffix('.tar.gz')
    with tarfile.open(path, 'r:gz') as archive:
        members = archive.getmembers()
        if len(members) != 2 or {m.name for m in members} != {name, 'SHA256SUMS'}:
            raise ValueError(f'{path.name}: unexpected archive members')
        if any(not m.isfile() or m.size > 64 * 1024 * 1024 for m in members):
            raise ValueError(f'{path.name}: invalid archive members')
        binary = archive.extractfile(name).read()
        checksums = archive.extractfile('SHA256SUMS').read().decode().split()
        if checksums != [hashlib.sha256(binary).hexdigest(), name]:
            raise ValueError(f'{path.name}: binary checksum mismatch')
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_bundle(path: Path, expected: str) -> None:
    if bundle_digest(path) != expected:
        raise ValueError(f'{path.name}: archive differs from pinned checksum')


def formula(manifest: dict) -> str:
    version = manifest['version']
    base = f'{RELEASES}/acshift-v{version}'
    blocks = []
    for os_name, brew_os in [('darwin', 'macos'), ('linux', 'linux')]:
        architectures = []
        for architecture, brew_arch in [('arm64', 'arm'), ('amd64', 'intel')]:
            asset = f'acshift-{os_name}-{architecture}.tar.gz'
            architectures.append(f'''    on_{brew_arch} do
      url "{base}/{asset}"
      sha256 "{manifest['sha256'][asset]}"
    end''')
        blocks.append(f'  on_{brew_os} do\n' + '\n\n'.join(architectures) + '\n  end')
    return f'''# Generated by scripts/release.py; update release.json and this file together.
class Acshift < Formula
  desc "Connect coding agents to the Applied Compute Shift router"
  homepage "https://shift.ac"
  version "{version}"
  license :cannot_represent

{chr(10).join(blocks)}

  def install
    os = OS.mac? ? "darwin" : "linux"
    arch = Hardware::CPU.arm? ? "arm64" : "amd64"
    libexec.install "acshift-#{{os}}-#{{arch}}" => "acshift"
    chmod 0755, libexec/"acshift"
    # The CLI compares these bytes before self-updating; pin them to this keg.
    (bin/"acshift").write_env_script libexec/"acshift",
                                   SHIFT_RELEASE_URL: "{base}"
  end

  def caveats
    <<~EOS
      To connect your coding agents to Shift, run:
        acshift install

      To upgrade this Homebrew installation, run:
        brew upgrade Applied-Compute/tap/acshift
    EOS
  end

  test do
    assert_equal "acshift {manifest['build_version']}", shell_output("#{{bin}}/acshift --version").strip
    assert_match "nothing is connected yet", shell_output("#{{bin}}/acshift doctor 2>&1", 1)
  end
end
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    prepare = commands.add_parser('prepare')
    prepare.add_argument('--version', required=True)
    prepare.add_argument('--build-version', required=True)
    prepare.add_argument('--bundles', type=Path, required=True)
    download = commands.add_parser('download')
    download.add_argument('--output', type=Path, required=True)
    download.add_argument('--published', action='store_true')
    commands.add_parser('check')
    args = parser.parse_args()
    if args.command == 'prepare':
        if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:\.[0-9]+)?', args.version):
            parser.error('version must be three or four numeric components')
        if not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9._-]{0,79}', args.build_version):
            parser.error('invalid CLI build version')
        manifest = {'version': args.version, 'build_version': args.build_version, 'sha256': {}}
        for platform in PLATFORMS:
            name = f'acshift-{platform}.tar.gz'
            manifest['sha256'][name] = bundle_digest(args.bundles / name)
        (ROOT / 'release.json').write_text(json.dumps(manifest, indent=2) + '\n')
        (ROOT / 'Formula/acshift.rb').write_text(formula(manifest))
        return
    manifest = json.loads((ROOT / 'release.json').read_text())
    if (ROOT / 'Formula/acshift.rb').read_text() != formula(manifest):
        parser.error('formula differs from release.json; run prepare again')
    if args.command == 'check':
        return
    args.output.mkdir(parents=True, exist_ok=True)
    base = f"{RELEASES}/acshift-v{manifest['version']}" if args.published else SOURCE
    for name, expected in manifest['sha256'].items():
        destination = args.output / name
        subprocess.run(['curl', '--fail', '--silent', '--show-error', '--location',
                        '--proto', '=https', '--proto-redir', '=https',
                        '--connect-timeout', '10', '--max-time', '120',
                        f'{base}/{name}', '--output', str(destination)], check=True, timeout=130)
        verify_bundle(destination, expected)
    print('All four bundles match the pinned release.')


if __name__ == '__main__':
    main()
